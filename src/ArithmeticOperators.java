public class ArithmeticOperators {
    public static void main(String[] args) {
        int a = 12;
        int b = 7;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b );

        double x = 7;
        double y = 2.9;
        System.out.println(x/y);
        System.out.println(x%y);
    }
}
