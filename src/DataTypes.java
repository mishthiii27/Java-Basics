public class DataTypes
{
    public static void main(String[] args) {
        int myNum = 121222;                               // intialization as we have a value to var
        int yourNum;
        char name = 'e';
                                              //Declaration i.e not givin a value but declaring a var
        yourNum = 120;
        System.out.println(myNum);
        System.out.println(yourNum);
        yourNum = 23456;
        System.out.println(yourNum);
        System.out.println(name);

        boolean isGood = false;
        System.out.println(isGood);

        float myFloat1 = 4.06f;
        double myDouble = 3.345566;
        System.out.println(myFloat1);
        System.out.println(myDouble);

        char age = 't';
        System.out.println(age);

        String greeting = "Good Morning y'all";
        String greet = "";
        System.out.println(greeting);
        System.out.println(greet );


    }
}
