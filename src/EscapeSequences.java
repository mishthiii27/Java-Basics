public class EscapeSequences {
    public static void main(String[] args) {
        System.out.println("hello \"Mish\" ");
        System.out.println("hello \'Mishthi\' ");
        System.out.println("hello \\Mishthi\\ ");
        System.out.println("hello \nMishthi... ");
        System.out.println("hello \tMishthi... ");
        System.out.println("hello \bMishthi... ");
    }
}
