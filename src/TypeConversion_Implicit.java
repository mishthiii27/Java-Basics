public class TypeConversion_Implicit {
    public static void main(String[] args) {
        float myFloat = 23;   //int to float
        float myFloat1 = 23L;   // long to float

        double myd = 234; // int to double
        double mydouble = 24.5; // float to double

        System.out.println(myFloat);
        System.out.println(myFloat1);
        System.out.println(myd);
        System.out.println(mydouble);
    }
}
